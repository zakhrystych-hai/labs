#include <iostream>
#include <cmath>

using namespace std;

int main()
{
    // Завдання 1. Integer10

    cout << "Завдання 1. Integer10\nвведіть тризначне число\n";

    // Вводимо тризначне число
    int n;
    cin >> n;

    // Знаходимо останню цифру
    int last = n % 10;

    // Ділимо число на 10
    int middle = (n / 10) % 10;

    // Виводимо спочатку останню, а потім середню цифру
    cout << last << " " << middle << endl;


    // Завдання 2. Boolean39

    // Перевірка можливості переходу ферзя
    // з одного поля шахової дошки на інше за один хід.

    int x1, y1, x2, y2;

    cout << "\nЗавдання 2. Boolean39\n";
    cout << "Перевірка ходу ферзя на шаховій дошці.\n";

    // Введення координат двох полів
    cout << "Введіть x1, y1: ";
    cin >> x1 >> y1;

    cout << "Введіть x2, y2: ";
    cin >> x2 >> y2;

    // Ферзь може рухатися:
    // 1. По горизонталі — y1 == y2
    // 2. По вертикалі — x1 == x2
    // 3. По діагоналі — різниця координат однакова
    bool result = (x1 == x2) ||
                  (y1 == y2) ||
                  (abs(x1 - x2) == abs(y1 - y2));

    // Виведення логічного значення
    cout << "Результат: " << result << endl;

    // Завдання 3. Math20

    cout << "\nЗавдання 3. Math20\n";

    // Константа числа pi
    const double pi = 3.14159265358979323846;

    // Змінні дійсного типу
    double x, y;

    // Введення значення x
    cout << "Введіть x: ";
    cin >> x;

    // Аргумент логарифма
    double logArgument = 2 * abs(x / 2);

    // Перевірка області допустимих значень:
    // аргумент логарифма повинен бути додатним
    // та не дорівнювати 1.
    if (logArgument <= 0 || logArgument == 1)
    {
        cout << "Помилка: для такого x вираз не має значення.\n";
        return 0;
    }

    // Переведення 127 градусів у радіани
    double angle = 127 * pi / 180 + 2 * x;

    // Обчислення математичного виразу
    // log_3(a) = ln(a) / ln(3)
    y = (2 * pow(3, x - 2)
         - sqrt(exp(2 * x) * abs(sin(angle))))
        / (log(logArgument) / log(3));

    // Виведення результату
    cout << "y = " << y << endl;

    return 0;
}
